/** A realistic AMyCharacter header with multiple macros and includes. */
const FULL_HEADER = `
// AMyCharacter.h — generated by UHT
#pragma once

#include "CoreMinimal.h"
#include "GameFramework/Character.h"
#include "MyCharacter.generated.h"

UCLASS(BlueprintType, Blueprintable)
class MYGAME_API AMyCharacter : public ACharacter
{
    GENERATED_BODY()

public:
    UPROPERTY(EditAnywhere, BlueprintReadWrite, Category="Stats")
    float Health;

    UPROPERTY(EditAnywhere, BlueprintReadWrite, Category="Stats", meta=(ClampMin="0", ClampMax="100"))
    float Stamina;

    UPROPERTY(EditAnywhere, BlueprintReadOnly, Category="Combat")
    AActor* TargetActor;

    UFUNCTION(BlueprintCallable, Category="Combat")
    void Attack();

    UFUNCTION(Server, Reliable, WithValidation)
    void ServerFire(float Damage);
};
`.trim();

