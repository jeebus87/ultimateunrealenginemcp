describe('parseCppFile — #include extraction', () => {
  it('extracts a double-quoted #include path', () => {
    const result = parseCppFile('#include "CoreMinimal.h"');
    expect(result.success).toBe(true);
    if (result.success) {
      expect(result.data.includes).toContain('CoreMinimal.h');
    }
  });

  it('extracts an angle-bracket #include path', () => {
    const result = parseCppFile('#include <vector>');
    expect(result.success).toBe(true);
    if (result.success) {
      expect(result.data.includes).toContain('<vector>');
    }
  });

  it('extracts all #include directives from FULL_HEADER in order', () => {
    const result = parseCppFile(FULL_HEADER);
    expect(result.success).toBe(true);
    if (result.success) {
      expect(result.data.includes).toEqual([
        'CoreMinimal.h',
        'GameFramework/Character.h',
        'MyCharacter.generated.h',
      ]);
    }
  });

  it('extracts both quoted and angled includes from PLAIN_HEADER', () => {
    const result = parseCppFile(PLAIN_HEADER);
    expect(result.success).toBe(true);
    if (result.success) {
      expect(result.data.includes).toContain('CoreMinimal.h');
      expect(result.data.includes).toContain('<vector>');
    }
  });

  it('returns empty includes array when no #include directives present', () => {
    const result = parseCppFile('// no includes here\nclass Foo {};');
    expect(result.success).toBe(true);
    if (result.success) {
      expect(result.data.includes).toHaveLength(0);
    }
  });
});

