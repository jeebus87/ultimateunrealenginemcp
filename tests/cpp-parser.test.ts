describe('parseCppFile — edge cases', () => {
  it('returns success for empty string input', () => {
    const result = parseCppFile('');
    expect(result.success).toBe(true);
    if (result.success) {
      expect(result.data.classes).toHaveLength(0);
      expect(result.data.includes).toHaveLength(0);
      expect(result.data.rawContent).toBe('');
    }
  });

  it('returns success for plain header with no UE macros', () => {
    const result = parseCppFile(PLAIN_HEADER);
    expect(result.success).toBe(true);
    if (result.success) {
      expect(result.data.classes).toHaveLength(0);
    }
  });

  it('preserves rawContent verbatim in the result', () => {
    const content = '// just a comment\n#include "A.h"';
    const result = parseCppFile(content);
    expect(result.success).toBe(true);
    if (result.success) {
      expect(result.data.rawContent).toBe(content);
    }
  });

  it('never throws — even on wildly malformed input', () => {
    expect(() => parseCppFile('{{{{UCLASS((((')).not.toThrow();
    expect(() => parseCppFile('UPROPERTY(\n\n\n')).not.toThrow();
    expect(() => parseCppFile(null as unknown as string)).not.toThrow();
  });
});

