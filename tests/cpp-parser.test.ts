describe('parseCppFile — UCLASS parsing', () => {
  it('parses UCLASS with no specifiers — specifiers: [], meta: {}', () => {
    const result = parseCppFile(UCLASS_EMPTY_SPECIFIERS);
    expect(result.success).toBe(true);
    if (result.success) {
      expect(result.data.classes).toHaveLength(1);
      const cls = result.data.classes[0]!;
      expect(cls.specifiers).toEqual([]);
      expect(cls.meta).toEqual({});
    }
  });

  it('parses UCLASS specifiers: ["BlueprintType", "Blueprintable"]', () => {
    const result = parseCppFile(FULL_HEADER);
    expect(result.success).toBe(true);
    if (result.success) {
      const cls = result.data.classes[0]!;
      expect(cls.specifiers).toContain('BlueprintType');
      expect(cls.specifiers).toContain('Blueprintable');
    }
  });

  it('parses UCLASS class name correctly', () => {
    const result = parseCppFile(FULL_HEADER);
    expect(result.success).toBe(true);
    if (result.success) {
      expect(result.data.classes[0]!.name).toBe('AMyCharacter');
    }
  });

  it('parses inheritance — parentClass: "ACharacter"', () => {
    const result = parseCppFile(FULL_HEADER);
    expect(result.success).toBe(true);
    if (result.success) {
      expect(result.data.classes[0]!.parentClass).toBe('ACharacter');
    }
  });

  it('captures only the first public parent from multiple inheritance', () => {
    const result = parseCppFile(MULTIPLE_INHERITANCE_HEADER);
    expect(result.success).toBe(true);
    if (result.success) {
      expect(result.data.classes[0]!.parentClass).toBe('AActor');
    }
  });

  it('parses UCLASS meta specifier into meta record', () => {
    const result = parseCppFile(UCLASS_WITH_META);
    expect(result.success).toBe(true);
    if (result.success) {
      const cls = result.data.classes[0]!;
      expect(cls.meta).toMatchObject({ ToolTip: 'My class description' });
    }
  });

  it('captures the line number of the class declaration', () => {
    const result = parseCppFile(FULL_HEADER);
    expect(result.success).toBe(true);
    if (result.success) {
      // Line numbers are 1-based; the class line exists somewhere > 1
      expect(result.data.classes[0]!.line).toBeGreaterThan(1);
    }
  });
});

