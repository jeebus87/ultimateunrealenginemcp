describe('parseCppFile — full integration', () => {
  it('parses FULL_HEADER: 1 class, 3 properties, 2 functions, 3 includes', () => {
    const result = parseCppFile(FULL_HEADER);
    expect(result.success).toBe(true);
    if (result.success) {
      expect(result.data.classes).toHaveLength(1);
      expect(result.data.classes[0]!.properties).toHaveLength(3);
      expect(result.data.classes[0]!.functions).toHaveLength(2);
      expect(result.data.includes).toHaveLength(3);
    }
  });

  it('DELEGATE_HEADER: DECLARE_DYNAMIC_MULTICAST_DELEGATE is skipped — 1 class with 1 property', () => {
    const result = parseCppFile(DELEGATE_HEADER);
    expect(result.success).toBe(true);
    if (result.success) {
      expect(result.data.classes).toHaveLength(1);
      expect(result.data.classes[0]!.properties).toHaveLength(1);
      expect(result.data.classes[0]!.functions).toHaveLength(0);
    }
  });

  it('parses all property names from FULL_HEADER in declaration order', () => {
    const result = parseCppFile(FULL_HEADER);
    expect(result.success).toBe(true);
    if (result.success) {
      const names = result.data.classes[0]!.properties.map((p) => p.name);
      expect(names).toEqual(['Health', 'Stamina', 'TargetActor']);
    }
  });

  it('parses all function names from FULL_HEADER in declaration order', () => {
    const result = parseCppFile(FULL_HEADER);
    expect(result.success).toBe(true);
    if (result.success) {
      const names = result.data.classes[0]!.functions.map((f) => f.name);
      expect(names).toEqual(['Attack', 'ServerFire']);
    }
  });

  it('Stamina UPROPERTY: specifiers exclude meta key, meta is a separate record', () => {
    const result = parseCppFile(FULL_HEADER);
    expect(result.success).toBe(true);
    if (result.success) {
      const stamina = result.data.classes[0]!.properties.find((p) => p.name === 'Stamina')!;
      // meta=(...) should NOT appear as a raw specifier string
      const hasRawMeta = stamina.specifiers.some((s) => s.startsWith('meta='));
      expect(hasRawMeta).toBe(false);
      // The meta record is populated instead
      expect(stamina.meta['ClampMin']).toBe('0');
    }
  });

  it('handles pathological multi-line collector — does not hang on 500+ line paren block', () => {
    // T-04-02 DoS mitigation: limit collector to 500 lines
    const manyLines = Array(600).fill('    SomeText,').join('\n');
    const pathological = `
#pragma once
UCLASS()
class AFoo : public AActor {
GENERATED_BODY()
public:
UPROPERTY(
${manyLines}
)
float X;
};`.trim();
    const result = parseCppFile(pathological);
    // Must not hang or throw — may succeed or fail gracefully
    expect(['success', 'object']).toContain(typeof result);
  });
});
